values
  ('SON_MAI', 'Sơn Mài'),
  ('FNB', 'F&B'),
  ('VAN_PHONG', 'Văn phòng')
on conflict (code) do update set name = excluded.name;

-- 2. BẢNG DANH MỤC THU CHI (CATEGORIES)
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  transaction_type text not null check (transaction_type in ('income','expense')),
  business_unit_id bigint references public.business_units(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- 3. BẢNG TÀI KHOẢN TIỀN / QUỸ (CASH ACCOUNTS)
create table if not exists public.cash_accounts (
  id bigint generated by default as identity primary key,
  name text not null,
  account_type text not null check (account_type in ('cash','bank','other')),
  opening_balance numeric(18,2) not null default 0,
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- 4. BẢNG GIAO DỊCH THU CHI (TRANSACTIONS)
create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  transaction_date date not null default current_date,
  business_unit_id bigint not null references public.business_units(id) on delete restrict,
  category_id bigint references public.categories(id) on delete set null,
  cash_account_id bigint references public.cash_accounts(id) on delete set null,
  transaction_type text not null check (transaction_type in ('income','expense')),
  amount numeric(18,2) not null check (amount > 0),
  payment_method text not null check (
    payment_method in ('cash','bank_transfer','card','other')
  ),
  description text,
  reference_no text,
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Tạo Index tăng tốc truy vấn theo ngày, mảng, người tạo
create index if not exists idx_transactions_date
  on public.transactions(transaction_date);
create index if not exists idx_transactions_unit_date
  on public.transactions(business_unit_id, transaction_date);
create index if not exists idx_transactions_created_by
  on public.transactions(created_by);
create index if not exists idx_transactions_type
  on public.transactions(transaction_type);

-- 5. TRIGGER TỰ ĐỘNG CẬP NHẬT UPDATED_AT
create or replace function public.handle_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists set_transactions_updated_at on public.transactions;
create trigger set_transactions_updated_at
before update on public.transactions
for each row execute function public.handle_updated_at();

